-- Muslima Free - dashboard: nearby search, part 2.
--
-- 1. dashboard_location_changes: user-profile-managment queues a member here (ProfileLocationChangeRecorder) when
--    their country, governorate or city changes (onboarding, profile edit). The dashboard re-indexes queued members
--    every app.location.sync-interval, so the full pass over every profile becomes a rare safety net.
-- 2. Device locations going stale are found through an index on their date instead of a full pass.
-- 3. More places, so members outside Egypt's big cities also get an approximate position.

CREATE TABLE dashboard_location_changes (
    user_id     CHAR(36)    NOT NULL,
    changed_at  DATETIME(6) NOT NULL,
    CONSTRAINT pk_dashboard_location_changes PRIMARY KEY (user_id),
    CONSTRAINT fk_dashboard_location_changes_profile FOREIGN KEY (user_id)
        REFERENCES user_profiles (user_id) ON DELETE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE INDEX ix_dashboard_location_changes_at ON dashboard_location_changes (changed_at);

CREATE INDEX ix_dashboard_locations_updated ON dashboard_member_locations (updated_at);

